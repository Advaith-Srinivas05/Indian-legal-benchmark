"""The human validation set: selection, artefacts, and refusing to self-certify.

The property these tests exist to protect is unusual, and it is the reason the
module exists at all: **this code must never produce a label.** Every threshold
in the pipeline was fitted to the same 100 documents it then classifies, and a
ground truth generated by the same system would reproduce that circularity in a
new file while looking like evidence.

So alongside the ordinary tests of determinism and coverage, there are tests
that the builder writes no labels, that the scorer treats an empty label file as
*not validated* rather than as agreement, and that a reviewer's work is never
overwritten by re-running the builder.

Offline: everything works on the JSON that :mod:`processing.process` already
wrote, so no PDF is opened and no OCR engine is needed.
"""

from __future__ import annotations

