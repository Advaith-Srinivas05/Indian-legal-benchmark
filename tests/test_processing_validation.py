def page(number, **overrides):
    """A processed page, as ``pages.json`` holds it."""
    data = {
        "page_number": number,
        "text": "Some ordinary statutory text on this page. " * 12,
        "char_count": 500,
        "alpha_char_count": 420,
        "has_text": True,
        "is_image_backed": False,
        "is_vector_outlined": False,
        "is_empty": False,
        "text_quality_suspect": False,
        "tables": [],
        "footnotes": [],
        "warnings": [],
        "orientation": {
            "declared_rotation": 0, "orientation": "upright",
            "sideways_line_ratio": 0.0, "reverse_line_ratio": 0.0,
            "horizontal_lines": 30, "direction_inconsistent": False,
            "measured_lines": 30, "needs_rotation": False,
            "source": "text_line_geometry",
        },
    }
    orientation = overrides.pop("orientation", None)
    data.update(overrides)
    if orientation:
        data["orientation"] = {**data["orientation"], **orientation}
    return data


def document(document_id, *, pdf_type="text_based", quality="good",
             content_language="en", year=2015, eligible=True, units=(),
             footnotes=()):
    return {
        "source": {
            "document_id": document_id, "title": f"Title of {document_id}",
            "category": "central_acts", "year": year, "jurisdiction": "India",
            "pdf_relpath": f"raw/{document_id}.pdf",
        },
        "extraction": {"pdf_type": pdf_type, "text_extraction_status": "ok"},
        "extraction_quality": {
            "classification": quality, "score": 0.9, "failed_checks": []},
        "content_language": {
            "content_language": content_language,
            "signals": {"function_word_rate": 0.5}},
        "ocr_decision": {"action": "use_extracted_text",
                         "text_source": "born_digital"},
        "eligible_for_indexing": eligible,
        "structure": {"units": list(units), "footnotes": list(footnotes)},
    }


def write_processed(root, document_id, doc, pages):
    directory = root / document_id
    directory.mkdir(parents=True, exist_ok=True)
    (directory / config.DOCUMENT_FILENAME).write_text(
        json.dumps(doc), encoding="utf-8")
    (directory / config.PAGES_FILENAME).write_text(
        json.dumps({"document_id": document_id, "pages": pages}),
        encoding="utf-8")


