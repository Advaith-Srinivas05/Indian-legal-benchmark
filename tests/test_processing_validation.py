class TestSelection:
    def test_selection_is_deterministic(self, records):
        first = validation.select(records, count=10)
        second = validation.select(records, count=10)
        assert [(p.document_id, p.page_number) for p in first] == \
            [(p.document_id, p.page_number) for p in second]

    def test_selection_does_not_depend_on_input_ordering(self, records):
        forward = validation.select(records, count=10)
        backward = validation.select(list(reversed(records)), count=10)
        assert {(p.document_id, p.page_number) for p in forward} == \
            {(p.document_id, p.page_number) for p in backward}

    def test_no_page_is_selected_twice(self, records):
        chosen = validation.select(records, count=12)
        keys = [(p.document_id, p.page_number) for p in chosen]
        assert len(keys) == len(set(keys))

    def test_the_rare_modes_are_reached_first(self, records):
        """A vector-outlined page must not be crowded out by clean ones.

        There is one such page in a hundred documents; if the round-robin spends
        its slots on the mode with thousands of candidates, the validation set
        cannot say anything about the mode most likely to be mishandled.
        """
        chosen = validation.select(records, count=6)
        modes = {p.selected_for for p in chosen}
        assert "vector_outlined" in modes

    def test_no_document_dominates_the_set(self, records):
        chosen = validation.select(records, count=14, max_per_document=2)
        counts = {}
        for selected in chosen:
            counts[selected.document_id] = counts.get(selected.document_id, 0) + 1
        assert max(counts.values()) <= 2

    def test_the_set_records_why_each_page_was_chosen(self, records):
        for selected in validation.select(records, count=8):
            assert selected.selected_for in validation.MODE_NAMES
            assert selected.selected_for in selected.modes

    def test_asking_for_more_than_exists_stops_cleanly(self, records):
        """It stops at the per-document cap, not at the page count.

        Five documents at three pages each is twelve selectable pages out of
        fourteen, and the two it declines are the fourth and fifth pages of the
        one long document — exactly what the cap is for.
        """
        chosen = validation.select(records, count=500)
        assert len(chosen) == 12
        assert len(chosen) < len(records)

    def test_without_a_cap_every_page_can_be_selected(self, records):
        chosen = validation.select(records, count=500, max_per_document=99)
        assert len(chosen) == len(records)

    def test_coverage_names_modes_with_no_page(self, records):
        report = validation.coverage(validation.select(records, count=4))
        assert set(report["modes_with_no_page"]) <= set(validation.MODE_NAMES)
        assert report["pages"] == 4

    def test_coverage_counts_every_mode_a_page_exhibits(self, records):
        chosen = validation.select(records, count=12)
        report = validation.coverage(chosen)
        assert sum(report["selected_for"].values()) == len(chosen)
        assert report["by_mode"]["scanned_page"] >= 1


