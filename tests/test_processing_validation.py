class TestExtractionCompletenessGate:
    """A document routed to OCR must not also be eligible for indexing.

    Found while building the human validation set, not by the benchmark: the
    review sheet showed a page whose extracted text was empty inside a document
    the system called eligible. Eight documents were in that state, the worst
    being the Nagaland Agriculture Produce Marketing regulations — text on 2 of
    68 pages, ``ocr_required``, and eligible.

    This is a consistency requirement, not a threshold. The pipeline already
    computed both facts and they contradicted each other.
    """

    @staticmethod
    def _result(action):
        from processing.models import (
            ExtractedDocument, OcrDecision, ProcessedDocument)

        return ProcessedDocument(
            document=None,
            extraction=ExtractedDocument(
                document_id="doc", page_count=68, pages=[],
                pdf_type="scanned", text_extraction_status="requires_ocr",
                orientation={"orientation_suspect": False}),
            language=type("L", (), {"eligible_for_indexing": True})(),
            quality=type("Q", (), {"classification": "good"})(),
            ocr_decision=OcrDecision(action=action, text_source="scan_without_ocr",
                                     reason="test"),
            ok=True,
        )

    @pytest.mark.parametrize("action", config.OCR_ACTIONS_BLOCKING_INDEX)
    def test_a_document_awaiting_ocr_is_not_eligible(self, action):
        assert not self._result(action).eligible_for_indexing

    @pytest.mark.parametrize("action", ["use_extracted_text", "review_text"])
    def test_a_document_not_awaiting_ocr_is_unaffected(self, action):
        assert self._result(action).eligible_for_indexing

    def test_the_blocking_actions_are_real_actions(self):
        from processing import ocr

        assert set(config.OCR_ACTIONS_BLOCKING_INDEX) <= set(ocr.ACTIONS)

    def test_the_gate_is_stated_once(self):
        """The same tuple decided OCR page counts and indexing eligibility in two
        places. Two copies of a policy drift."""
        from processing import ocr

        assert ocr.config.OCR_ACTIONS_BLOCKING_INDEX is \
            config.OCR_ACTIONS_BLOCKING_INDEX


