class TestConfusionMatrices:
    def test_a_matrix_counts_every_pair(self):
        block = validation_score.confusion(
            [("GOOD", "good"), ("GOOD", "good"), ("BAD", "bad")])
        assert block["matrix"]["GOOD"]["good"] == 2
        assert block["matrix"]["BAD"]["bad"] == 1
        assert block["n"] == 3

    def test_margins_add_up(self):
        block = validation_score.confusion(
            [("GOOD", "good"), ("BAD", "good"), ("BAD", "bad")])
        assert block["human_totals"] == {"BAD": 2, "GOOD": 1}
        assert block["system_totals"] == {"bad": 1, "good": 2}

    def test_every_classifier_gets_a_matrix(self):
        payload = {"entries": [entry("a", 1)]}
        labels = {("a", 1): {"label": "GOOD", "legal_critical_errors": [],
                             "notes": ""}}
        result = validation_score.score(payload, labels)
        for name, _ in validation_score.CLASSIFIERS:
            assert name in result["by_classifier"]
            assert result["by_classifier"][name]["n"] == 1

    def test_labels_are_broken_down_by_failure_mode(self):
        payload = {"entries": [entry("a", 1, modes=("poor_ocr_layer",
                                                    "scanned_page"))]}
        labels = {("a", 1): {"label": "BAD", "legal_critical_errors": [],
                             "notes": ""}}
        result = validation_score.score(payload, labels)
        assert result["by_failure_mode"]["poor_ocr_layer"] == {"BAD": 1}
        assert result["by_failure_mode"]["scanned_page"] == {"BAD": 1}
        assert result["by_failure_mode"]["born_digital_clean"] == {}

    def test_legal_critical_errors_are_tallied(self):
        payload = {"entries": [entry("a", 1), entry("a", 2)]}
        labels = {
            ("a", 1): {"label": "BAD",
                       "legal_critical_errors": ["altered_negation"], "notes": ""},
            ("a", 2): {"label": "BAD",
                       "legal_critical_errors": ["altered_negation",
                                                 "wrong_date"], "notes": ""},
        }
        result = validation_score.score(payload, labels)
        assert result["legal_critical_errors"]["altered_negation"] == 2
        assert result["legal_critical_errors"]["wrong_date"] == 1


class TestScoreReport:
    def test_a_scored_report_leads_with_false_acceptances(self):
        payload = {"entries": [entry("a", 1, eligible=True)]}
        labels = {("a", 1): {"label": "BAD",
                             "legal_critical_errors": ["wrong_number"],
                             "notes": "penalty read as 5000 not 500"}}
        markdown = validation_score.render_markdown(
            validation_score.score(payload, labels))
        assert "The number that decides this" in markdown
        assert "false acceptances" in markdown
        assert "penalty read as 5000 not 500" in markdown

    def test_a_clean_report_says_so_without_overclaiming(self):
        payload = {"entries": [entry("a", 1, eligible=False)]}
        labels = {("a", 1): {"label": "BAD", "legal_critical_errors": [],
                             "notes": ""}}
        markdown = validation_score.render_markdown(
            validation_score.score(payload, labels))
        assert "No false acceptances" in markdown
        assert "deliberately richer in damage than the corpus average" in markdown

    def test_a_partial_review_is_marked_partial(self):
        payload = {"entries": [entry("a", 1), entry("a", 2)]}
        labels = {("a", 1): {"label": "GOOD", "legal_critical_errors": [],
                             "notes": ""}}
        markdown = validation_score.render_markdown(
            validation_score.score(payload, labels))
        assert "Partial" in markdown
        assert "not a random sample" in markdown
