"""Builds a miniature ``data/`` tree for the processing tests.

The processing stages read the corpus through the artefacts the ingestion phase
produced — ``manifest.json`` for what is stored and where, and the discovery
inventory for the year and state each document belongs to. Rather than mocking
those readers, these helpers write real files in the real shape, so a change to
either format is caught here instead of in production.

Everything is offline: PDFs are generated by :mod:`tests.pdfbuild`.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Optional, Sequence

from ingestion import config as ingestion_config
from ingestion.utils import sha256_file

from . import pdfbuild


def add_document(
    data_dir: Path,
    document_id: str,
    *,
    category: str = "central_acts",
    document_type: Optional[str] = None,
    title: Optional[str] = None,
    pages: Optional[Sequence[str]] = None,
    kind: str = "text",
    year: Optional[int] = 1999,
    jurisdiction: str = "India",
) -> dict:
    """Write one document's PDF and return its manifest/inventory entries.

    *kind* selects the fixture shape: ``text``, ``scanned``, ``mixed``,
    ``blank`` or ``corrupt``.
    """
    document_type = document_type or ingestion_config.CATEGORY_TO_DOCUMENT_TYPE[category]
    relpath = f"raw/indiacode/{category}/{document_id}/{document_id}.pdf"
    path = data_dir / relpath
    path.parent.mkdir(parents=True, exist_ok=True)

    body = list(pages) if pages else [_DEFAULT_BODY]
    if kind == "text":
        pdfbuild.text_pdf(path, body)
    elif kind == "scanned":
        pdfbuild.scanned_pdf(path, page_count=3)
    elif kind == "mixed":
        pdfbuild.mixed_pdf(path, text_pages=body, image_pages=2)
    elif kind == "blank":
        pdfbuild.blank_pdf(path, page_count=2)
    elif kind == "corrupt":
        pdfbuild.corrupt_pdf(path)
    else:                                        # pragma: no cover - test bug
        raise ValueError(f"unknown fixture kind {kind!r}")

    manifest_entry = {
        "document_id": document_id,
        "provider": "India Code",
        "source_url": f"https://www.indiacode.nic.in/handle/123456789/{abs(hash(document_id)) % 99999}",
        "primary_pdf_url": "https://www.indiacode.nic.in/bitstream/x.pdf",
        "handle": "123456789/1",
        "category": category,
        "document_type": document_type,
        "title": title or document_id.replace("-", " ").title(),
        "sha256": sha256_file(path),
        "bytes": path.stat().st_size,
        "pdf_relpath": relpath,
        "metadata_relpath": f"raw/indiacode/{category}/{document_id}/metadata.json",
        "language": "en",
        "language_source": "indiacode_metadata_title",
    }
    inventory_entry = {
        "document_id": document_id,
        "title": manifest_entry["title"],
        "document_type": document_type,
        "jurisdiction": jurisdiction,
        "year": year,
        "collection_name": jurisdiction,
        "enactment_date": f"{year}-01-01" if year else None,
    }
    return {"manifest": manifest_entry, "inventory": inventory_entry}


def write_corpus(data_dir: Path, entries: Sequence[dict], *, inventory: bool = True) -> Path:
    """Write ``manifest.json`` and (optionally) the discovery inventory."""
    data_dir = Path(data_dir)
    manifest = {
        "schema_version": ingestion_config.MANIFEST_SCHEMA_VERSION,
        "generated_at": "2026-01-01T00:00:00+00:00",
        "documents": {e["manifest"]["document_id"]: e["manifest"] for e in entries},
    }
    (data_dir / ingestion_config.MANIFEST_FILENAME).write_text(
        json.dumps(manifest, indent=2), encoding="utf-8")

    if inventory:
        directory = data_dir / ingestion_config.DISCOVERY_SUBDIR
        directory.mkdir(parents=True, exist_ok=True)
        (directory / ingestion_config.INVENTORY_FILENAME).write_text(
            json.dumps({
                "schema_version": ingestion_config.DISCOVERY_SCHEMA_VERSION,
                "documents": [e["inventory"] for e in entries],
            }, indent=2),
            encoding="utf-8",
        )
    return data_dir


_DEFAULT_BODY = (
    "THE SAMPLE ACT, 1999\n"
    "An Act to provide for the regulation of samples.\n"
    "1. Short title and extent. This Act may be called the Sample Act, 1999 and "
    "extends to the whole of India.\n"
    "2. Definitions. In this Act, unless the context otherwise requires, the "
    "expressions used shall have the meanings assigned to them.\n"
    "3. Power to make rules. The Central Government may, by notification in the "
    "Official Gazette, make rules for carrying out the purposes of this Act.\n"
)
